import { useEffect } from "react";
import {
  BRAND,
  PERSONAL_DATA_CONSENT_VERSION,
  PERSONAL_DATA_DOCUMENT_URLS,
  PERSONAL_DATA_OPERATOR,
  PERSONAL_DATA_RETENTION_DAYS,
  SECTION_IDS,
} from "../consts";

import "./PersonalDataDocument.css";

export type PersonalDataDocumentKind = "consent" | "policy";

export const PersonalDataDocument = ({
  kind,
}: {
  kind: PersonalDataDocumentKind;
}) => {
  const title =
    kind === "consent"
      ? "Согласие на обработку персональных данных"
      : "Политика обработки персональных данных";

  useEffect(() => {
    const previousTitle = document.title;
    document.title = `${title} — ${BRAND.name}`;
    return () => {
      document.title = previousTitle;
    };
  }, [title]);

  const operator = (
    <>
      {PERSONAL_DATA_OPERATOR.name}
      {PERSONAL_DATA_OPERATOR.address && (
        <>, адрес: {PERSONAL_DATA_OPERATOR.address}</>
      )}
      . Контакт по вопросам обработки данных и отзыва согласия:{" "}
      <a href={`mailto:${PERSONAL_DATA_OPERATOR.email}`}>
        {PERSONAL_DATA_OPERATOR.email}
      </a>
      .
    </>
  );

  return (
    <div className="personal-data-page">
      <header className="personal-data-header">
        <a href={`${process.env.PUBLIC_URL || ""}/`}>{BRAND.name}</a>
        <a href={`${process.env.PUBLIC_URL || ""}/#${SECTION_IDS.contact}`}>
          К форме заявки <span aria-hidden="true">↗</span>
        </a>
      </header>
      <main className="personal-data-content">
        <p className="personal-data-meta">
          Редакция от 14 октября 2026 · {PERSONAL_DATA_CONSENT_VERSION}
        </p>
        <h1>{title}</h1>
        {kind === "consent" ? (
          <>
            <p className="personal-data-lead">
              Отмечая отдельный чекбокс в форме и отправляя заявку, я свободно,
              своей волей и в своём интересе даю оператору согласие на обработку
              указанных ниже персональных данных.
            </p>
            <h2>1. Оператор</h2>
            <p>{operator}</p>
            <h2>2. Цель и состав данных</h2>
            <p>
              Цель — получить и рассмотреть мою заявку, ответить на неё и
              согласовать консультацию. Согласие распространяется на имя,
              рабочий email, выбранную задачу и удобную дату и время звонка,
              которые я указываю в форме.
            </p>
            <p>
              Вместе с заявкой фиксируются факт согласия, дата и время его
              предоставления и версия этого текста.
            </p>
            <h2>3. Действия с данными</h2>
            <p>
              Разрешаю сбор, запись, систематизацию, накопление, хранение,
              уточнение, извлечение и использование данных для указанной цели, а
              также блокирование, удаление и уничтожение. Обработка может
              осуществляться с использованием средств автоматизации и без них.
            </p>
            <p>
              Заявка поступает на сервер оператора. Данные не используются для
              рекламных рассылок, не публикуются и не передаются третьим лицам,
              кроме случаев, прямо предусмотренных законодательством РФ.
              Согласие на распространение данных я не предоставляю.
            </p>
            <h2>4. Срок действия и отзыв</h2>
            <p>
              Согласие действует с момента отправки заявки до завершения её
              рассмотрения, но не более {PERSONAL_DATA_RETENTION_DAYS} дней,
              либо до отзыва согласия, если он поступит раньше. Для отзыва
              достаточно направить письмо на указанный выше email с темой «Отзыв
              согласия» и email, указанным в заявке.
            </p>
            <p>
              При достижении цели или отзыве согласия оператор прекращает
              обработку и уничтожает данные в срок, предусмотренный статьёй 21
              Федерального закона № 152-ФЗ, как правило, не позднее 30 дней.
              Если закон предусматривает самостоятельное основание для
              дальнейшей обработки, она допускается только в этих пределах.
            </p>
            <p>
              Подробные условия и права изложены в{" "}
              <a href={PERSONAL_DATA_DOCUMENT_URLS.policy}>
                политике обработки персональных данных
              </a>
              . Это согласие является отдельным документом.
            </p>
          </>
        ) : (
          <>
            <p className="personal-data-lead">
              Эта политика описывает обработку данных посетителей, которые
              отправляют заявку через форму на сайте {BRAND.name}.
            </p>
            <h2>1. Оператор и правовое основание</h2>
            <p>{operator}</p>
            <p>
              Обработка осуществляется на основании отдельного согласия
              посетителя в соответствии с Федеральным законом от 27.07.2006 №
              152-ФЗ «О персональных данных». Политика доступна без регистрации.
            </p>
            <h2>2. Какие данные и для чего обрабатываются</h2>
            <p>
              Оператор обрабатывает имя, рабочий email, выбранную задачу и
              удобную дату и время звонка исключительно для получения и
              рассмотрения заявки, ответа на неё и согласования консультации.
              Факт согласия, время его предоставления и версия документа
              сохраняются вместе с заявкой для подтверждения согласия.
            </p>
            <p>
              Оператор не запрашивает паспортные данные, специальные категории
              персональных данных или биометрические данные. Данные заявки не
              используются для рекламы, профилирования или публичного
              распространения.
            </p>
            <p>
              Для защиты формы от злоупотреблений IP-адрес соединения временно
              используется в оперативной памяти сервера для ограничения частоты
              запросов в пределах 15-минутного окна. Он не записывается в
              заявку; счётчики периодически очищаются. Основание — защита
              законных интересов оператора по пункту 7 части 1 статьи 6 Закона №
              152-ФЗ при соблюдении прав посетителей.
            </p>
            <h2>3. Порядок обработки и защита</h2>
            <p>
              Данные поступают через форму на сервер оператора и обрабатываются
              с использованием средств автоматизации и без них. Выполняемые
              действия: сбор, запись, систематизация, накопление, хранение,
              уточнение, извлечение, использование, блокирование, удаление и
              уничтожение.
            </p>
            <p>
              Оператор ограничивает доступ к заявкам уполномоченными лицами,
              обеспечивает конфиденциальность и принимает необходимые правовые,
              организационные и технические меры защиты по статье 19 Закона №
              152-ФЗ. При сборе данных граждан РФ оператор обязан соблюдать
              требования о локализации, установленные частью 5 статьи 18 этого
              закона.
            </p>
            <p>
              Сервер сайта сохраняет заявки для оператора без пересылки во
              внешние сервисы. Предоставление уполномоченным государственным
              органам допускается только в случаях, предусмотренных законом.
            </p>
            <h2>4. Сроки хранения и уничтожение</h2>
            <p>
              Заявка хранится до завершения её рассмотрения, но не более{" "}
              {PERSONAL_DATA_RETENTION_DAYS} дней с момента получения, либо до
              отзыва согласия, если он поступит раньше. Данные удаляются при
              достижении цели, отзыве согласия или выявлении неправомерной
              обработки в сроки статьи 21 Закона № 152-ФЗ. При достижении цели
              или отзыве согласия срок уничтожения, как правило, составляет не
              более 30 дней, если отсутствует иное законное основание.
            </p>
            <h2>5. Права посетителя</h2>
            <p>
              Посетитель вправе получить сведения об обработке своих данных,
              потребовать их уточнения, блокирования или уничтожения при наличии
              оснований, отозвать согласие и обжаловать действия оператора в
              Роскомнадзор или суд.
            </p>
            <p>
              Обращения принимаются на email оператора. Укажите email,
              использованный в заявке, и суть обращения. Ответ предоставляется в
              срок, установленный законом; для запроса сведений об обработке — в
              течение 10 рабочих дней с возможностью мотивированного продления
              не более чем на 5 рабочих дней.
            </p>
            <h2>6. Согласие и изменения политики</h2>
            <p>
              До отправки заявки посетитель знакомится с{" "}
              <a href={PERSONAL_DATA_DOCUMENT_URLS.consent}>
                отдельным согласием на обработку данных
              </a>{" "}
              и отмечает обязательный чекбокс. Без этого заявка не отправляется.
              Актуальная редакция политики размещается на этой странице;
              изменение цели обработки требует соответствующего правового
              основания.
            </p>
          </>
        )}
      </main>
    </div>
  );
};
